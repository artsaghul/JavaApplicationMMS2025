class Calculator {
    public int calculate(int a, int b) { return a + b; } // 2 integers
    public int calculate(int a, int b, int c) { return a + b + c; } // 3 integers
    public double calculate(double a, double b) { return a + b; } // 2 doubles
    public int calculate(int a, int b, boolean multiply) { return a * b; } // multiply 2 integers
}
